#ifndef __MODBUS_MAP_H
#define __MODBUS_MAP_H

/*
 * ============================================================================
 * modbus_map.h — Modbus 寄存器地址映射表
 * ============================================================================
 *
 * 【用途】把"从机地址(寄存器号)"翻译成"人看得懂的物理量"。上层应用(app_sensor.c)
 *   读传感器时, 不再记魔数, 直接用 MODBUS_REG_TEMPERATURE / MODBUS_REG_HUMIDITY。
 *
 * 【适用设备】KTH2-R30 温湿度变送器(RS-485 输出, 出厂固件已内置 Modbus-RTU 从机)。
 *   变送器内部自带 MCU 完成温湿度采集, 对外只暴露 RS-485 + Modbus-RTU 接口,
 *   所以网关只要按标准 Modbus 主站去读就行, 不用关心它内部用什么传感元件。
 *
 * 【寄存器表】(从机地址 0x01, 波特率 9600 8N1)
 *   0x0300: 温度, int16_t(有符号 16 位), 单位 0.1℃
 *           例: 读回 235 → 23.5℃;  读回 -105(0xFF97) → -10.5℃
 *   0x0301: 湿度, int16_t, 单位 0.1%RH
 *           例: 读回 523 → 52.3%RH
 *
 * 【为什么地址是 0x0300 而不是 0x0000】
 *   这是 KTH2-R30 的厂家寄存器约定(同类变送器还有 0x0000 / 0x0001 的版本,
 *   甚至有的用 0x0001 起算且带 0x8000 偏移)。写代码前必须查该型号手册的
 *   "寄存器表", 不能凭经验猜 —— 这是嵌入式对接最常踩的坑之一。
 *
 * 【读取帧示例】(功能码 03, 一次读 2 个寄存器, 从地址 0x0300 开始)
 *   主站发: 01 03 03 00 00 02 <CRC L> <CRC H>
 *           └从机 └03 └起始0x0300 └数量2 └CRC16
 *   从机回: 01 03 04 <温度H> <温度L> <湿度H> <湿度L> <CRC L> <CRC H>
 *           └从机 └03 └字节数4 └两个寄存器共 4 字节
 *
 * 【易错点】寄存器值是大端序(高字节在前), 且温度是有符号数 ——
 *   解析时必须按 int16_t 处理, 否则零下温度会被当成一个巨大的正数。
 * ============================================================================
 */

#include "stm32f1xx_hal.h"   /* 提供 int16_t 等标准整型定义 */

#define MODBUS_REG_TEMPERATURE      0x0300  /* 温度寄存器 (只读, int16_t, 0.1℃) */
#define MODBUS_REG_HUMIDITY         0x0301  /* 湿度寄存器 (只读, int16_t, 0.1%RH) */

#endif
