volatile uint32_t g_usart2_irq_fired;

void USART2_IRQHandler(void)
{
    g_usart2_irq_fired++;

    /* IDLE = RS-485 一帧完整到达 (先读 SR 再读 DR 才能清标志) */
    if (USART2->SR & USART_SR_IDLE) {
        (void)USART2->SR;
        (void)USART2->DR;
        BSP_RS485_OnIdleISR();
    }

    HAL_UART_IRQHandler(&huart2);
}

/* DMA1_Ch4: printf (USART1_TX) 完成中断 → 续发下一段 */
void DMA1_Channel4_IRQHandler(void)
{
    HAL_DMA_IRQHandler(&hdma_usart1_tx);
}

/* USART1: printf DMA 段发送完成后的 TC 中断。
 * F1 HAL 的 DMA-TX 完成链: DMA TC → 置 CR1_TCIE → 本中断 →
 * HAL_UART_IRQHandler → UART_EndTransmit_IT → HAL_UART_TxCpltCallback。
 * 缺了它, 第一段发完 gState 永远停在 BUSY_TX, 日志只出第一个字符。 */
void USART1_IRQHandler(void)
{
    HAL_UART_IRQHandler(&huart1);
}

/* DMA1_Ch6: RS-485 (USART2_RX) 循环接收, 出错时由 HAL 回调处理 */
void DMA1_Channel6_IRQHandler(void)
{
    HAL_DMA_IRQHandler(&hdma_usart2_rx);
}

