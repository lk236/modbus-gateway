/* ======================== CRC32 ======================== */

/* 一次性算完整段数据的 CRC32。
 * 【算法步骤】初值取全 1 → 逐字节查表更新 → 最后整体按位取反（出异或）。
 *   - crc ^ data[i] 的"低 8 位"作查表索引（& 0xFF 确保落在 0~255）
 *   - crc >> 8 是"反射式"算法要求的右移（对应多项式的 LSB-first 处理）
 * 用于：整个固件的完整性校验（pack_firmware.py 与 Bootloader 对称使用）。 */
uint32_t CRC32_ZIP(const uint8_t *data, uint32_t len)
{
    uint32_t crc = 0xFFFFFFFF;                    /* 初值：全 1（注意不是 0） */
    for (uint32_t i = 0; i < len; i++) {
        /* 查表 + 移位异或，一次处理一个字节 */
        crc = crc32_table[(crc ^ data[i]) & 0xFF] ^ (crc >> 8);
    }
    return crc ^ 0xFFFFFFFF;                      /* 出异或：整体取反，得到最终值 */
}

/* 分段累加计算 CRC32。
 * 【和 CRC32_ZIP 的区别】它不做"初值全 1"和"最终取反"，
 *   专门用于"分多次喂数据"的场景：调用方自己维护 crc 变量，
 *   首次传 0xFFFFFFFF 进去，中间来多少数据就喂多少，最后再手工取反。
 *   这样就能对大文件/流式数据做增量校验，而不必一次性读进内存。 */
uint32_t CRC32_ZIP_Update(uint32_t crc, const uint8_t *data, uint32_t len)
{
    for (uint32_t i = 0; i < len; i++) {
        crc = crc32_table[(crc ^ data[i]) & 0xFF] ^ (crc >> 8);
    }
    return crc;   /* 直接返回中间值，由调用方决定何时取反 */
}

/* ======================== CRC16-Modbus ======================== */

/* Modbus 标准 CRC16。
 * 【与 CRC32 的差异】
 *   - 初值 0xFFFF，且【最后不取反】（CRC32 要取反，别记混）；
 *   - 查表后是"表值"整体赋给 crc（不是再异或移位），因为表里已经含了移位结果。
 * 【用在哪】OTA 的每个 512 字节数据块的 block_crc；
 *   以及下位机 Modbus RTU 报文尾部的 CRC（两处算法一致，可互相校验）。 */
uint16_t CRC16_Modbus(const uint8_t *data, uint32_t len)
{
    uint16_t crc = 0xFFFF;                        /* 初值：全 1（不取反） */
    for (uint32_t i = 0; i < len; i++) {
        /* 高字节右移出来，与查表结果异或 —— Modbus 的标准写法 */
        crc = (crc >> 8) ^ crc16_table[(crc ^ data[i]) & 0xFF];
    }
    return crc;                                   /* 直接返回，不做出异或 */
}
