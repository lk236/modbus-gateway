/* ============================================================================
 * ota_crc.c — CRC32-ZIP + CRC16-Modbus 实现
 *
 * 【这个文件干什么？】
 *   给 OTA 提供两套校验算法。校验是为了"确认数据没在传输/存储过程中被改坏"：
 *   发送方算一个值，接收方按同样算法再算一遍，两者相等才认为数据完整。
 *
 * 【为什么是两个不同的 CRC？各用在哪？】
 *   - CRC32-ZIP：给"整个固件"做校验。数据量大、要求很强，32 位碰撞概率极低。
 *     上位机 pack_firmware.py 打包时算一次写进文件头；下位机 Bootloader 收完后
 *     整体再算一次，和头里的比对，一致才真正写入正式固件区。
 *   - CRC16-Modbus：给"每个 512 字节数据块"做校验。它是 Modbus 协议自带的 CRC，
 *     实现现成、代价小，适合"每包都要校验"的高频场景。
 *   —— 这体现了工程上常见的"分层校验"：块级用轻量 CRC，整体用强 CRC。
 *
 * 【参数表】
 * CRC32-ZIP: 多项式 0x04C11DB7, 初值 0xFFFFFFFF, 出异或 0xFFFFFFFF
 *   (与 bsp_w25q64.c 中 CRC32 一致, 和 STM32 硬件 CRC 单元兼容)
 *
 * CRC16-Modbus: 多项式 0x8005, 初值 0xFFFF, 出异或 0x0000
 *   (与 Modbus RTU 协议 CRC 标准一致)
 *
 * 【实现方式：查表法】
 *   逐位计算要对每个字节做 8 次循环，太慢；预先算出"任意字节(0~255)对应的
 *   中间值"存成 256 项的表，运行时只做几次移位异或 + 查表，快一个数量级。
 *   代价是 ROM 里多占 1KB(CRC32表) + 512B(CRC16表)——对嵌入式完全可以接受。
 * 【表的生成方式】用生成多项式对 0~255 逐个"左移8次(或右移8次)"
 *   递推算出，是纯离线计算，程序里只需存结果。
 * 【易错点】下面两张表的"大小端/字节序"约定不同，别搞混：
 *   crc32_table 按"反射(LSB-first)"方式生成，配合 crc>>8 使用；
 *   crc16_table 是标准 Modbus 表，配合 (crc>>8) 使用。
 *   用错表或用错移位方向都会算出错值。
 * ============================================================================
 */
